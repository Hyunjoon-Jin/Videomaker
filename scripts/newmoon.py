"""Meeus, Astronomical Algorithms ch.49 — 삭(new moon) 시각.

음력 달의 크기(29일/30일)를 알아야 '에도 체류 24일'이 맞는지 판정된다.
삭이 든 날이 그 달의 초하루이므로, 연속한 두 삭의 날짜 차이가 달의 크기다.
조선 후기 시헌력은 북경(동경 116°25′) 기준이므로 그 지방 평시로 잰다.
"""
import math

D = math.radians


def nm(k):
    """k번째 삭의 JDE (TT). k=0은 2000-01-06."""
    T = k / 1236.85
    jde = (2451550.09766 + 29.530588861 * k
           + 0.00015437 * T**2 - 0.000000150 * T**3 + 0.00000000073 * T**4)
    E = 1 - 0.002516 * T - 0.0000074 * T**2
    M = 2.5534 + 29.10535670 * k - 0.0000014 * T**2 - 0.00000011 * T**3      # 태양 평균근점이각
    Mp = 201.5643 + 385.81693528 * k + 0.0107582 * T**2 + 0.00001238 * T**3 - 0.000000058 * T**4
    F = 160.7108 + 390.67050284 * k - 0.0016118 * T**2 - 0.00000227 * T**3 + 0.000000011 * T**4
    O = 124.7746 - 1.56375588 * k + 0.0020672 * T**2 + 0.00000215 * T**3
    M, Mp, F, O = D(M), D(Mp), D(F), D(O)
    s = (-0.40720 * math.sin(Mp)
         + 0.17241 * E * math.sin(M)
         + 0.01608 * math.sin(2 * Mp)
         + 0.01039 * math.sin(2 * F)
         + 0.00739 * E * math.sin(Mp - M)
         - 0.00514 * E * math.sin(Mp + M)
         + 0.00208 * E * E * math.sin(2 * M)
         - 0.00111 * math.sin(Mp - 2 * F)
         - 0.00057 * math.sin(Mp + 2 * F)
         + 0.00056 * E * math.sin(2 * Mp + M)
         - 0.00042 * math.sin(3 * Mp)
         + 0.00042 * E * math.sin(M + 2 * F)
         + 0.00038 * E * math.sin(M - 2 * F)
         - 0.00024 * E * math.sin(2 * Mp - M)
         - 0.00017 * math.sin(O)
         - 0.00007 * math.sin(Mp + 2 * M))
    A = [(299.77 + 0.107408 * k - 0.009173 * T**2, 0.000325),
         (251.88 + 0.016321 * k, 0.000165),
         (251.83 + 26.651886 * k, 0.000164),
         (349.42 + 36.412478 * k, 0.000126),
         (84.66 + 18.206239 * k, 0.000110),
         (141.74 + 53.303771 * k, 0.000062),
         (207.14 + 2.453732 * k, 0.000060),
         (154.84 + 7.306860 * k, 0.000056),
         (34.52 + 27.261239 * k, 0.000047),
         (207.19 + 0.121824 * k, 0.000042),
         (291.34 + 1.844379 * k, 0.000040),
         (161.72 + 24.198154 * k, 0.000037),
         (239.56 + 25.513099 * k, 0.000035),
         (331.55 + 3.592518 * k, 0.000023)]
    add = sum(c * math.sin(D(a)) for a, c in A)
    return jde + s + add


def deltaT(y):
    """TT - UT (초). 1700~1800 구간은 Espenak/Meeus 다항식."""
    t = y - 1700
    return 8.83 + 0.1603 * t - 0.0059285 * t**2 + 0.00013336 * t**3 - t**4 / 1174000


def cal(jd):
    """율리우스일 → 그레고리력 (년, 월, 일, 시)."""
    jd += 0.5
    Z, F = int(jd), jd - int(jd)
    if Z < 2299161:
        A = Z
    else:
        al = int((Z - 1867216.25) / 36524.25)
        A = Z + 1 + al - al // 4
    B = A + 1524
    C = int((B - 122.1) / 365.25)
    Dd = int(365.25 * C)
    E = int((B - Dd) / 30.6001)
    day = B - Dd - int(30.6001 * E) + F
    mo = E - 1 if E < 14 else E - 13
    yr = C - 4716 if mo > 2 else C - 4715
    d = int(day)
    return yr, mo, d, (day - d) * 24


BEIJING = 116 + 25 / 60  # 시헌력 기준 자오선. 지방 평시 = UT + 경도/15
OFF = BEIJING / 15 / 24  # 일 단위


def moons(k0, k1):
    out = []
    for k in range(k0, k1):
        jde = nm(k)
        y = cal(jde)[0]
        jd_ut = jde - deltaT(y) / 86400
        out.append((k, cal(jd_ut + OFF)))
    return out


