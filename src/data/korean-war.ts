/** 경과일 → 날짜 문자열 */
export function dateLabel(day: number): string {
  const base = new Date(Date.UTC(1950, 5, 25));
  const d = new Date(base.getTime() + Math.floor(day) * 86400000);
  return `${d.getUTCFullYear()}. ${d.getUTCMonth() + 1}. ${d.getUTCDate()}.`;
}

