/**
 * 수도권 전철 노선 색과 아이콘 글자.
 *
 * 색은 각 운영기관이 쓰는 노선 색이다. 사람들이 노선도에서 이미
 * 외운 색이라 **바꾸면 안 된다** — 2호선이 초록이 아니면 그 순간
 * 지도가 아니라 그림이 된다.
 *
 * 열쇠는 OSM `ref` 값 그대로다(`scripts/prep-metro.py`). 영문·약칭이
 * 섞여 있어서(`I2`·`U`·`W`·`Silim`·`E`) 여기서 사람 이름으로 옮긴다.
 *
 * **`U`는 우이신설이 아니라 의정부경전철이다.** 첫 판에서 그렇게
 * 짚었다가 틀렸다. 우이신설은 `W`고, network 태그가 없어서 받을 때
 * 아예 빠져 있었다.
 */
export interface LineStyle {
  /** 노선 색 */
  c: string;
  /** 아이콘 안에 넣는 글자 */
  t: string;
  /** 아이콘 글자 색. 밝은 노선만 어둡게 */
  ink?: string;
}

