/**
 * 쇼츠 안전 영역.
 *
 * 실제 쇼츠 재생 화면을 보고서야 알았다. 시계는 위쪽 칩 줄(구독·라이브·
 * 렌즈·트렌드) 뒤에 깔려 있었고, 범례와 고지 줄은 채널명과 설명 줄이
 * 통째로 덮고 있었다. 1080×1920 캔버스에 다 그려놓고 "다 보인다"고
 * 여긴 것인데, 보는 사람 화면에서는 그 자리가 남의 것이다.
 *
 * ── 어떻게 쟀나 ──────────────────────────────────────
 * 쇼츠는 9:16 영상을 화면 폭에 맞춰 띄우고 위아래를 검게 남긴다(잘리지는
 * 않는다). 919×1919 스크린샷에서 영상은 y=142~1776을 차지했다. 화면
 * 좌표를 디자인 좌표로 옮기면 (y_screen - 142) / 1634 * 1920이다.
 *
 *   위쪽 칩 줄 끝      화면 345  →  디자인 238
 *   채널명 줄 시작     화면 1680 →  디자인 1807
 *   오른쪽 버튼 기둥   화면 x 800~890, y 1130~1620
 *                     →  디자인 x 940~1046, y 1161~1737
 *
 * 기기마다 다르므로 여유를 얹는다. 아래는 그 여유까지 넣은 값이다.
 *
 * ── 규칙 ─────────────────────────────────────────────
 * 글자는 TOP과 BOTTOM 사이에만 둔다. 지도는 그 밖으로 나가도 된다 —
 * 가장자리가 좀 가려져도 그림은 읽힌다. 가려지면 안 되는 것은 숫자와
 * 문장이다.
 */

/**
 * 위쪽 UI가 끝나는 자리. 글자는 이 아래에서 시작한다.
 *
 * 잰 값은 238이었고 처음에는 300을 썼다. 62px 여유인데, 기기마다 칩 줄
 * 높이가 다르고 뒤로가기 화살표가 한 줄 더 붙는 화면도 있어 그걸로는
 * 얇다. 352로 올렸다 — 잰 값에서 114px.
 */
export const SAFE_TOP = 352;

/**
 * 아래쪽 UI가 시작하는 자리. 글자는 이 위에서 끝난다.
 *
 * 잰 값은 1807(채널명 줄 시작)이었고 처음에는 1760을 썼다. 47px 여유다.
 * 그런데 아래 UI는 채널명 한 줄이 아니라 [채널명·구독] [영상 제목]
 * [음악 정보]가 쌓인 덩어리고, 제목이 두 줄이 되면 그만큼 위로 올라온다.
 * 1680으로 내렸다 — 잰 값에서 127px.
 */
export const SAFE_BOTTOM = 1680;

/** 좌우 여백. 화면을 꽉 채우는 기기에서 잘려도 남을 만큼 준다. */
export const SAFE_X = 68;

/**
 * 글자를 앉히는 왼쪽 자리.
 *
 * SAFE_X와 다른 값이다. SAFE_X는 '여기 안쪽이면 안 잘린다'는 한계선이고,
 * 이건 '여기서 시작해야 읽힌다'는 여백이다. 한계선에 딱 붙여 쓰면
 * 안 잘리기는 하는데 글이 화면 왼쪽 모서리에 쏠려 붙어 읽기가 나쁘다.
 *
 * 1080의 9.6%. 큰 숫자와 자막이 같은 선에서 시작하므로 이 값 하나만
 * 바꾸면 열 편의 왼쪽 정렬이 같이 움직인다.
 */
export const TEXT_X = 104;

/**
 * 오른쪽 버튼 기둥(좋아요·댓글·공유·리믹스)이 차지하는 폭.
 * 이 띠 안에서는 글자가 오른쪽으로 여기까지만 간다.
 */
export const SAFE_RIGHT = 180;

/** 버튼 기둥이 걸리는 세로 구간 */
export const RAIL_TOP = 1130;
export const RAIL_BOTTOM = 1760;

/** 아래쪽 글자 블록이 쓸 수 있는 바닥 여백 (style의 bottom 값) */
export const BOTTOM_INSET = 1920 - SAFE_BOTTOM; // 240

/**
 * 마무리 화면의 바닥 여백.
 *
 * 마무리는 고지 줄이 없어서 BOTTOM_INSET보다 조금 더 띄워도 되고,
 * 오히려 그래야 마지막 문장이 채널명 줄과 안 붙는다.
 */
export const OUTRO_PAD = 280;
